/** @brief Gets the 32-bit value from the value buffer.
 *
 */
static uint32_t get_uint32_val(const uint8_t *input)
{
    uint32_t output = 0U;
    output          = *(input);
    output <<= 8;
    output |= *(input + 1u);
    output <<= 8;
    output |= *(input + 2u);
    output <<= 8;
    output |= *(input + 3u);
    return output;
}

/** @brief Gets the 16-bit value from the value buffer.
 *
 */
static uint16_t get_uint16_val(const uint8_t *input)
{
    uint16_t output = 0U;
    output          = *input;
    output <<= 8;
    output |= *(input + 1u);
    return output;
}

// Function taken from MbedTLS
static int get_len(const unsigned char **p, const unsigned char *end, size_t *len)
{
    if ((end - *p) < 1)
    {
        return (PSA_ERROR_INVALID_ARGUMENT);
    }

    if ((**p & 0x80u) == 0u)
    {
        *len = *(*p)++;
    }
    else
    {
        switch (**p & 0x7Fu)
        {
            case 1:
                if ((end - *p) < 2)
                {
                    return (PSA_ERROR_INVALID_ARGUMENT);
                }

                *len = (*p)[1];
                (*p) += 2;
                break;

            case 2:
                if ((end - *p) < 3)
                {
                    return (PSA_ERROR_INVALID_ARGUMENT);
                }

                *len = ((size_t)(*p)[1] << 8) | (*p)[2];
                (*p) += 3;
                break;

            case 3:
                if ((end - *p) < 4)
                {
                    return (PSA_ERROR_INVALID_ARGUMENT);
                }

                *len = ((size_t)(*p)[1] << 16) | ((size_t)(*p)[2] << 8) | (*p)[3];
                (*p) += 4;
                break;

            case 4:
                if ((end - *p) < 5)
                {
                    return (PSA_ERROR_INVALID_ARGUMENT);
                }

                *len = ((size_t)(*p)[1] << 24) | ((size_t)(*p)[2] << 16) | ((size_t)(*p)[3] << 8) | (*p)[4];
                (*p) += 5;
                break;

            default:
                return (PSA_ERROR_INVALID_ARGUMENT);
        }
    }
    if (*len > (size_t)(end - *p))
    {
        return (PSA_ERROR_INVALID_ARGUMENT);
    }
    return (0);
}
// Function taken from MbedTLS
static int get_tag(const unsigned char **p, const unsigned char *end, size_t *len, uint8_t tag)
{
    if ((end - *p) < 1)
    {
        return (PSA_ERROR_INVALID_ARGUMENT);
    }

    if (**p != tag)
    {
        return (PSA_ERROR_INVALID_ARGUMENT);
    }

    (*p)++;

    return (get_len(p, end, len));
}

static psa_status_t loadFW(uint8_t *fw)
{
    sss_sscp_tunnel_t tunnelCtx;
    psa_status_t psa_status = PSA_ERROR_INVALID_ARGUMENT;
    uint32_t resultState = 0u;

    nboot_sb3_header_t *block0 = (nboot_sb3_header_t *)fw;

    do
    {
        if (sss_sscp_tunnel_context_init(&tunnelCtx, &g_ele_ctx.sssSession, kSSS_tunnel_type_EdgelockFW) != kStatus_SSS_Success)
        {
          PRINTF("sss_sscp_tunnel_context_init failed\r\n");
            break;
        }

        if (sss_sscp_tunnel(&tunnelCtx, (uint8_t *)fw, block0->imageTotalLength, &resultState) != kStatus_SSS_Success)
        {
            PRINTF("sss_sscp_tunnel failed\r\n");
            sss_sscp_tunnel_context_free(&tunnelCtx);
            break;
        }

        /* If all steps before passes without break, then consider it as success*/
        psa_status = PSA_SUCCESS;

    } while (false);

    /* FREE TUNNEL CONTEXT */
    sss_sscp_tunnel_context_free(&tunnelCtx);

    return psa_status;
}

static psa_status_t get_ele_fw_version(uint8_t *ele_fw_version)
{
    sss_mgmt_t mgmtContext        = {0u};
    psa_status_t psa_status = PSA_ERROR_INVALID_ARGUMENT;

    size_t datalen = 8u;

    /* PropertyId of Edgelock Firmware version */
    uint32_t propertyId = 0x51u;

    do
    {
        if (sss_mgmt_context_init(&mgmtContext, &g_ele_ctx.sssSession) != kStatus_SSS_Success)
        {
            break;
        }

        /* READ FUSE */
        if (sss_mgmt_get_property(&mgmtContext, propertyId, ele_fw_version, &datalen) != kStatus_SSS_Success)
        {
            break;
        }

        /* If all steps before passes without break, then consider it as success*/
        psa_status = PSA_SUCCESS;

    } while (false);

    /* FREE MGMT CONTEXT */
    sss_mgmt_context_free(&mgmtContext);

    return psa_status;
}

